let SC=null;
function newScene(kind,Wd,Hd){
  const g=v=>{const a=[];for(let x=0;x<Wd;x++)a.push(new Array(Hd).fill(v));return a};
  return{kind,W:Wd,H:Hd,T:g(0),ST:g('g'),B:g(null),COL:g(null),HT:g(0),HZ:g(0),SD:g(null),units:[],objs:[],projs:[],attacks:[],fx:[],texts:[],parts:[],flash:new Map(),
    t:0,shake:0,banner:null,pack:{coins:0,copper:0,iron:0},cam:{x:0,y:0},failT:0,saved:[],danger:new Set(),prompt:null,player:null,boss:null,exit:null,done:false};
}
const inB=(x,y)=>x>=0&&y>=0&&x<SC.W&&y<SC.H;
// Heights. HT is the level; a stair tile (SD = the uphill direction) sits half a level above its HT and joins HT to HT+1.
// Call setHeights() once a layout is built: it fills HZ (ground height in px) and EARLY (tiles drawn one step early).
function setHeights(sc){
  for(let x=0;x<sc.W;x++)for(let y=0;y<sc.H;y++)sc.HZ[x][y]=(sc.HT[x][y]+(sc.SD[x][y]?.5:0))*ZL;
  const lv=(x,y)=>x>=0&&y>=0&&x<sc.W&&y<sc.H&&sc.T[x][y]?sc.HZ[x][y]+(sc.T[x][y]===2?1e3:0):-1e9;
  sc.EARLY=[];for(let x=0;x<sc.W;x++){sc.EARLY.push([]);for(let y=0;y<sc.H;y++){const h=lv(x,y);sc.EARLY[x].push(sc.T[x][y]===1&&h<=lv(x-1,y)&&h<=lv(x,y-1))}}
}
// Can a unit step from tile a to the neighbouring tile b? Same level, or along a stair's axis onto/off it.
function canStep(ax,ay,bx,by){
  if(!inB(ax,ay)||!inB(bx,by))return false;
  const sa=SC.SD[ax][ay],sb=SC.SD[bx][by],ha=SC.HT[ax][ay],hb=SC.HT[bx][by],dx=bx-ax,dy=by-ay;
  if(!sa&&!sb)return ha===hb;
  if(sb&&!sa){if(dx===sb.x&&dy===sb.y)return ha===hb;if(dx===-sb.x&&dy===-sb.y)return ha===hb+1;return false}
  if(sa&&!sb){if(dx===sa.x&&dy===sa.y)return hb===ha+1;if(dx===-sa.x&&dy===-sa.y)return hb===ha;return false}
  // stair to stair: along the same axis, same level or one up
  if(sa.x!==sb.x||sa.y!==sb.y)return false;
  if(dx===sa.x&&dy===sa.y)return hb===ha||hb===ha+1;if(dx===-sa.x&&dy===-sa.y)return hb===ha||hb===ha-1;return ha===hb}
const floorAt=(x,y)=>inB(x,y)&&SC.T[x][y]===1;
function unitAt(x,y,self){for(const u of SC.units)if(u!==self&&!u.gone&&u.tx===x&&u.ty===y)return u;return null}
const free=(x,y,self)=>floorAt(x,y)&&!SC.B[x][y]&&!unitAt(x,y,self);
function placeObj(o){SC.objs.push(o);if(o.block)SC.B[o.x][o.y]=o;return o}
function removeObj(o){SC.objs=SC.objs.filter(q=>q!==o);if(SC.B[o.x][o.y]===o)SC.B[o.x][o.y]=null}
const heroes=()=>SC.units.filter(u=>u.kind==='hero');
const inRoom=(r,x,y)=>x>=r.x0&&x<=r.x1&&y>=r.y0&&y<=r.y1;

let UID=0;
function mkUnit(o){const u=Object.assign({id:++UID,tx:0,ty:0,prog:1,dur:.13,face:{x:0,y:1},hp:100,maxhp:100,st:100,stDelay:0,inv:0,flash:0,atkT:0,cd:0,skillCd:0,dash:0,drink:0,down:false,revT:0,holdT:0,carrying:null,stun:0,team:0,moveT:0},o);u.fx=u.tx;u.fy=u.ty;SC.units.push(u);return u}

