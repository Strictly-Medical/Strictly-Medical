  for(const[x,y]of M.falls)placeObj({type:'fall',x,y,kOff:.4});
  const g=sc.gate;for(const[dx,dy]of[[-2,1],[2,1]]){const[x,y]=nearFree(g.x+dx,g.y+dy,sc.HT[g.x][g.y]);placeObj({type:'brazier',x,y,block:true})}
  const gd=B.guild.door;for(const dx of[-2,2]){const[x,y]=nearFree(gd.x+dx,gd.y+1,sc.HT[gd.x][gd.y]);placeObj({type:'brazier',x,y,block:true})}
  const npc=(id,name,role,at,look,face,talk,scale)=>{const[x,y]=nearFree(at[0],at[1]);return mkUnit({kind:'npc',team:2,id,name,role,tx:x,ty:y,look,face,talk,scale})};
