// Lanternhold on the Dawnspire Isle. The layout comes from MAPS.dawnspire (js/map-dawnspire.js), generated by
// art/maps/overworld.py from the reference painting: ground type and level per tile, stairs, building spots and landmarks.
// Find the nearest walkable tile to (x,y) on the given level (or any level).
function nearFree(x,y,lv){for(let r=0;r<8;r++)for(let dx=-r;dx<=r;dx++)for(let dy=-r;dy<=r;dy++){if(Math.max(Math.abs(dx),Math.abs(dy))!==r)continue;const nx=x+dx,ny=y+dy;if(free(nx,ny)&&!SC.SD[nx][ny]&&(lv===undefined||SC.HT[nx][ny]===lv))return[nx,ny]}return[x,y]}
